const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base=process.env.RELEASE_QA_URL || 'http://127.0.0.1:5192/';
const out=path.resolve(__dirname,'../../output/release-20260928');
let browser,page;
const report={base,checkedAt:new Date().toISOString(),checks:[],errors:[]};
const pass=name=>{report.checks.push(name);console.log('PASS '+name);};
(async()=>{
 browser=await chromium.launch({headless:true,channel:'chrome'});
 const context=await browser.newContext({viewport:{width:1440,height:960},locale:'zh-CN',timezoneId:'Asia/Shanghai'});
 page=await context.newPage();page.setDefaultTimeout(20000);page.on('pageerror',e=>report.errors.push(e.message));page.on('dialog',d=>d.accept());
 await page.goto(base);
 await page.getByRole('button',{name:'苏州',exact:true}).click();
 await page.getByLabel('出发日期',{exact:true}).fill('2026-10-06');
 await page.getByRole('button',{name:'生成我的路线',exact:true}).click();
 await page.locator('.plan-panel .itinerary-stop').first().waitFor();
 await page.waitForFunction(()=>navigator.serviceWorker.controller,null,{timeout:45000});
 pass('production service worker installed');
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('anytravel-web:current-trip')||'null')?.trips[0]?.snapshot?.accommodations?.length>0,null,{timeout:70000});
 await page.getByRole('radio',{name:'住宿',exact:true}).click();
 const stay=page.locator('.stay-card.selected');
 await stay.getByRole('button',{name:'我已订好'}).click();
 await stay.getByLabel('实际支付总额（可留空）').fill('1288.50');
 await stay.getByLabel('住宿订单备注（可留空）').fill('QA synthetic record');
 await stay.getByRole('button',{name:'确认已预订'}).click();
 assert.match(await stay.innerText(),/1,288\.5/);
 assert.ok(await stay.getByRole('button',{name:'预订已锁定'}).isDisabled());
 await page.getByRole('radio',{name:'费用',exact:true}).click();
 assert.match(await page.locator('.cost-summary').innerText(),/1,288\.5/);
 await page.getByRole('radio',{name:'住宿',exact:true}).click();
 await stay.getByRole('button',{name:'撤销确认'}).click();
 assert.equal(await stay.locator('.booking-confirmation').count(),0);
 pass('booking confirmation, decimal actual cost, lock and undo');
 await page.getByRole('button',{name:'旅途偏好与价格渠道'}).click();
 const settings=page.getByRole('dialog',{name:'旅途偏好与服务'});
 assert.match(await settings.innerText(),/本次有结果/);
 assert.doesNotMatch(await settings.innerText(),/全部.*正常/);
 await settings.getByRole('button',{name:'关闭设置'}).click();
 pass('channel status reflects observed quotes');
 await page.getByRole('radio',{name:'行程',exact:true}).click();
 await page.getByLabel('一句话调整行程').fill('预算改为每人2500元，其他条件保持不变');
 await page.getByRole('button',{name:'发送调整'}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('anytravel-web:current-trip')||'null')?.trips[0]?.draft?.budgetPerPerson===2500,null,{timeout:45000});
 pass('natural language action applied through real assistant');
 await page.locator('[data-map-ready=true]').waitFor({timeout:30000});
 await page.getByRole('button',{name:'存进旅册',exact:true}).click();
 await page.screenshot({path:out+'/production-desktop.png'});
 await page.setViewportSize({width:390,height:844});
 await page.waitForTimeout(500);
 await page.screenshot({path:out+'/production-mobile.png'});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
 pass('production desktop and mobile render');
 // A newly opened handbook must load offline from precached lazy chunks.
 await context.setOffline(true); await page.reload();
 await page.getByRole('button',{name:'继续上次旅程',exact:true}).click();
 await page.locator('.plan-panel .itinerary-stop').first().waitFor();
 await page.getByRole('button',{name:'随行手册',exact:true}).click();
 const book=page.getByRole('dialog',{name:'随行手册',exact:true});
 await book.getByRole('navigation',{name:'手册章节'}).getByRole('button',{name:'同行账本',exact:true}).click();
 await page.frameLocator('iframe[title="同行账本：记账、同行人和结算"]').getByRole('button',{name:'添加同行人',exact:true}).first().waitFor();
 pass('offline reload restores saved plan, lazy handbook and ledger');
 assert.deepEqual(report.errors,[]);
 report.status='passed';await browser.close();fs.writeFileSync(out+'/production-ui.json',JSON.stringify(report,null,2));
})().catch(async e=>{report.status='failed';report.failure=e.stack;console.error(e);try{await page.screenshot({path:out+'/production-failure.png',fullPage:true});fs.writeFileSync(out+'/production-failure.txt',await page.locator('body').innerText());}catch{}fs.writeFileSync(out+'/production-ui.json',JSON.stringify(report,null,2));await browser?.close();process.exitCode=1;});
